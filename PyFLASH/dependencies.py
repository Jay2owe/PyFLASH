"""Detect and repair declared dependencies from installed package metadata."""
from importlib import invalidate_caches
from importlib.metadata import PackageNotFoundError, distribution, requires, version
from pathlib import Path
import os
import subprocess
import sys

from packaging.requirements import Requirement


def _install_target(requirement):
    """Keep requested extras while removing our own activation marker."""
    extras='['+','.join(sorted(requirement.extras))+']' if requirement.extras else ''
    target=requirement.name+extras
    return target+(' @ '+requirement.url if requirement.url else str(requirement.specifier))


def _extra_dependencies(requirement,installed):
    """Check the installed backend's dependencies for its requested extras."""
    if installed is None or not requirement.extras:
        return []
    records=[]
    for text in requires(requirement.name) or []:
        dependency=Requirement(text)
        if dependency.marker and not any(dependency.marker.evaluate({'extra':extra})
                                        for extra in ('',*sorted(requirement.extras))):
            continue
        try:
            current=version(dependency.name)
        except PackageNotFoundError:
            current=None
        records.append({'requirement':str(dependency),'package':dependency.name,
                        'version':current,'compatible':current is not None and
                        dependency.specifier.contains(current)})
    return records


def registry():
    """Package requirements are generated by the build from pyproject.toml."""
    records = {}
    extras = distribution('PyFLASH-analysis').metadata.get_all('Provides-Extra') or []
    for text in requires('PyFLASH-analysis') or []:
        requirement = Requirement(text)
        if requirement.marker and not any(requirement.marker.evaluate({'extra': extra}) for extra in
            ('', *extras)):
            continue
        groups = [extra for extra in extras
                  if requirement.marker and requirement.marker.evaluate({'extra': extra})
                  and not requirement.marker.evaluate({'extra': ''})]
        records[requirement.name] = {'package': requirement.name,
            'requirement': str(requirement), 'groups': groups or ['core'],
            'specifier': str(requirement.specifier)}
    return records


def check(group=None):
    """Report missing and incompatible versions without importing libraries."""
    entries = registry()
    groups = {name for entry in entries.values() for name in entry['groups']}
    if group is not None and group not in groups:
        raise ValueError(f'Unknown dependency group {group!r}. Valid: {", ".join(sorted(groups))}')
    records = []
    for entry in entries.values():
        if group and group not in entry['groups']:
            continue
        entry = dict(entry)
        try:
            installed = version(entry['package'])
        except PackageNotFoundError:
            installed = None
        requirement = Requirement(entry['requirement'])
        extra_dependencies=_extra_dependencies(requirement,installed)
        compatible = (installed is not None and requirement.specifier.contains(installed)
                      and all(item['compatible'] for item in extra_dependencies))
        entry.update(version=installed, compatible=compatible,
                     extra_dependencies=extra_dependencies,
                     optional='core' not in entry['groups'],
                     repair=None if compatible else f'python -m pip install "{_install_target(requirement)}"')
        records.append(entry)
    return records


def repair(package):
    """Install exactly one declared requirement, then verify the resulting version."""
    entries = registry()
    match = next((entry for name, entry in entries.items() if name.lower().replace('_', '-') ==
                  package.lower().replace('_', '-')), None)
    if match is None:
        raise ValueError(f'Unknown dependency {package!r}. Valid: {", ".join(entries)}')
    requirement = Requirement(match['requirement'])
    actual = Path(sys.prefix) / 'python.exe'
    executable = str(actual) if os.name == 'nt' and actual.is_file() else sys.executable
    command = [executable, '-m', 'pip', 'install', _install_target(requirement)]
    completed = subprocess.run(command, capture_output=True, text=True,
                               creationflags=getattr(subprocess, 'CREATE_NO_WINDOW', 0))
    if completed.returncode:
        raise RuntimeError(completed.stderr or completed.stdout)
    invalidate_caches()
    # Optional backend probes must be retried after a repair.
    image_io = sys.modules.get('PyFLASH.image_io')
    if image_io is not None:
        image_io._OPTIONAL_MODULES.clear()
    optional = sys.modules.get('PyFLASH._optional')
    if optional is not None:
        optional._CACHE.clear()
    record = next(entry for entry in check() if entry['package'] == match['package'])
    if not record['compatible']:
        raise RuntimeError(f"Installed dependency still does not satisfy {match['requirement']}.")
    return {**record, 'command': command, 'log': completed.stdout}
